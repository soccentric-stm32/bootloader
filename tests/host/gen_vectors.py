#!/usr/bin/env python3
#
# gen_vectors.py - regenerate tests/host/test_vectors.c (BSAFE-006)
#
# Author:  Sandesh Ghimire <sandesh@soccentric.com>
# Date:    2026-11-05
#
# The host tests use a fixed test key (not the development key) so that
# they can sign headers in C with uECC_sign().  This script also signs one
# header with tools/mkimage.py, which proves that what the Python host tool
# produces is what the C verifier accepts, and records SHA-256 reference
# digests from hashlib.
#
#   python3 tests/host/gen_vectors.py
#
# Needs the Python "cryptography" package.  The output is committed; the
# host test build itself needs no Python.

import hashlib
import pathlib
import struct
import sys
import zlib

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "tools"))

import mkimage  # noqa: E402
from cryptography.hazmat.primitives.asymmetric import ec  # noqa: E402

# secp256r1 group order; the scalar is derived from a fixed label so the
# file is reproducible.
ORDER = 0xFFFFFFFF00000000FFFFFFFFFFFFFFFFBCE6FAADA7179E84F3B9CAC2FC632551
SCALAR = int.from_bytes(
    hashlib.sha256(b"soccentric bootloader host test key").digest(),
    "big") % ORDER

BOOT_APP_LOAD_ADDR = 0x0800C000
BOOT_RAM_END = 0x20080000


def c_array(name: str, data: bytes, static: bool = False) -> str:
    rows = []
    for offset in range(0, len(data), 12):
        rows.append("    " + ", ".join(f"0x{b:02x}"
                                      for b in data[offset:offset + 12]))
    prefix = "static " if static else ""
    return (f"{prefix}const uint8_t {name}[{len(data)}] = {{\n" +
            ",\n".join(rows) + "\n};\n")


def main() -> int:
    key = ec.derive_private_key(SCALAR, ec.SECP256R1())
    point = mkimage.public_point(key)

    # The same 16-byte body that test_main.c's make_slot() programs.
    body = struct.pack("<II", BOOT_RAM_END, BOOT_APP_LOAD_ADDR + 0x101) + \
        bytes(8)
    header = bytearray(mkimage.HEADER_SIZE)
    struct.pack_into("<IHHIIIIIII", header, 0, mkimage.MAGIC,
                     mkimage.HEADER_VERSION_UNSIGNED, mkimage.HEADER_SIZE,
                     mkimage.IMAGE_TYPE_APPLICATION, 0x00010000, len(body),
                     zlib.crc32(body) & 0xFFFFFFFF, BOOT_APP_LOAD_ADDR,
                     BOOT_APP_LOAD_ADDR + 0x101, 1)
    header[56:60] = b"test"
    signed = mkimage.sign_header(bytes(header), body, key,
                                 security_counter=7)

    messages = [
        b"",
        b"abc",
        b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq",
        bytes(i & 0xFF for i in range(1000)),
    ]

    out = [
        "/*\n"
        " * test_vectors.c - generated by tests/host/gen_vectors.py; "
        "do not edit.\n"
        " *\n"
        " * Host-test signing key (not the development key), a header "
        "signed by\n"
        " * tools/mkimage.py and SHA-256 reference digests from hashlib.\n"
        " */\n\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "#include \"signing_key.h\"\n"
        "#include \"test_vectors.h\"\n\n",
        c_array("boot_signing_pubkey", point),
        f"\nconst uint32_t boot_signing_key_id = "
        f"0x{mkimage.key_id(point):08x}UL;\n\n",
        c_array("test_signing_privkey", SCALAR.to_bytes(32, "big")),
        "\n",
        c_array("test_python_body", body),
        "\n",
        c_array("test_python_header", signed),
        "\n",
    ]
    for index, message in enumerate(messages):
        out.append(c_array(f"sha_msg_{index}", message or b"\0",
                           static=True))
        out.append(c_array(f"sha_digest_{index}",
                           hashlib.sha256(message).digest(), static=True))
    out.append("\nconst test_sha_vector_t test_sha_vectors[] = {\n")
    for index, message in enumerate(messages):
        out.append(f"    {{ sha_msg_{index}, {len(message)}U, "
                   f"sha_digest_{index} }},\n")
    out.append("};\n\nconst size_t test_sha_vector_count =\n"
               "    sizeof(test_sha_vectors) / sizeof(test_sha_vectors[0]);"
               "\n")

    (HERE / "test_vectors.c").write_text("".join(out))
    print(f"wrote {HERE / 'test_vectors.c'} "
          f"(key id 0x{mkimage.key_id(point):08x})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
